"""Provider-neutral, evidence-grounded analyst with a deterministic default."""

from __future__ import annotations

import json
import os
import re
import urllib.error
import urllib.request
from datetime import datetime, timezone
from typing import Any, Dict, List, Protocol

from .models import AIAnalysis, Decision, EvidenceReport, PolicyResult, validate_evidence_payload


PROMPT_VERSION = "1.0"
MAX_EVIDENCE_CHARS = 12000


class AnalystProvider(Protocol):
    name: str
    model: str

    def analyze(self, payload: Dict[str, Any]) -> Dict[str, Any]: ...


class MockProvider:
    name = "mock"
    model = "deterministic-mock"

    def analyze(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        policy = payload["policy"]
        reasons = policy["reasons"]
        status = policy["status"]
        refs = policy["evidence_references"] or ["changed_files"]
        if reasons:
            summary = f"Deterministic policy result is {status} based on {len(reasons)} triggered rule(s)."
            findings = [reason["message"] for reason in reasons]
            action = "Address the triggered rules and rerun the evidence checks."
            rollback = ["Restore the previous version if the change must be withdrawn."]
        else:
            summary = "All required evidence checks passed and no policy rule was triggered."
            findings = []
            action = "Proceed with normal human release review."
            rollback = ["Revert the release to the previous commit if unexpected behavior appears."]
        return {
            "summary": summary,
            "decision": status,
            "confidence": 0.95 if reasons else 0.90,
            "affected_components": payload["changed_files"],
            "evidence_references": refs,
            "prioritized_findings": findings,
            "recommended_action": action,
            "rollback_plan": rollback,
            "limitations": ["Generated by the deterministic mock provider; no external model was called."],
        }


class OpenAICompatibleProvider:
    """Minimal optional JSON HTTP provider, enabled only by an explicit endpoint."""

    name = "openai-compatible"

    def __init__(self, endpoint: str, model: str, api_key: str = ""):
        self.endpoint = endpoint
        self.model = model
        self.api_key = api_key

    def analyze(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        request_body = json.dumps({"model": self.model, "temperature": 0,
                                   "messages": [{"role": "system", "content": _system_prompt()},
                                                {"role": "user", "content": json.dumps(payload)}]}).encode()
        request = urllib.request.Request(self.endpoint, data=request_body,
                                         headers={"Content-Type": "application/json"}, method="POST")
        if self.api_key:
            request.add_header("Authorization", "Bearer " + self.api_key)
        with urllib.request.urlopen(request, timeout=30) as response:
            document = json.loads(response.read(1_000_001).decode())
        content = document["choices"][0]["message"]["content"]
        return json.loads(content) if isinstance(content, str) else content


def analyze(report: EvidenceReport, policy: PolicyResult, scenario_summary: str = "") -> AIAnalysis:
    provider = provider_from_environment()
    payload = build_model_input(report, policy, scenario_summary)
    limitations: List[str] = []
    try:
        raw = provider.analyze(payload)
        analysis = validate_output(raw, report, policy, provider.name, provider.model)
    except (OSError, ValueError, KeyError, TypeError, json.JSONDecodeError, urllib.error.URLError) as exc:
        limitations.append(f"Analyst provider unavailable or invalid: {type(exc).__name__}.")
        analysis = fallback_analysis(report, policy, provider.name, provider.model, limitations)
    return analysis


def provider_from_environment() -> AnalystProvider:
    provider = os.environ.get("CHANGELENS_MODEL_PROVIDER", "mock").strip().lower()
    if provider == "mock":
        return MockProvider()
    endpoint = os.environ.get("CHANGELENS_MODEL_ENDPOINT", "").strip()
    if endpoint:
        return OpenAICompatibleProvider(endpoint, os.environ.get("CHANGELENS_MODEL", "local-model"),
                                        os.environ.get("CHANGELENS_MODEL_API_KEY", ""))
    raise OSError("no explicitly configured analyst provider endpoint")


def build_model_input(report: EvidenceReport, policy: PolicyResult, scenario_summary: str) -> Dict[str, Any]:
    factual = report.to_dict()
    validate_evidence_payload(factual)
    for tool in factual["tools"]:
        tool["stdout"] = _sanitize(tool.get("stdout", ""))[:2000]
        tool["stderr"] = _sanitize(tool.get("stderr", ""))[:2000]
        tool["command"] = _sanitize(tool.get("command", ""))[:500]
    payload = {
        "scenario_summary": scenario_summary,
        "changed_files": report.changed_files,
        "tools": factual["tools"],
        "tests": factual["tests"],
        "security_findings": report.security_findings,
        "api_findings": report.api_findings,
        "performance": report.performance,
        "policy": policy.to_dict(),
    }
    serialized = json.dumps(payload)
    if len(serialized) > MAX_EVIDENCE_CHARS:
        payload["tools"] = [{key: value for key, value in tool.items() if key not in {"stdout", "stderr"}}
                             for tool in payload["tools"]]
        payload["security_findings"] = payload["security_findings"][:50]
        payload["api_findings"] = payload["api_findings"][:50]
        payload["changed_files"] = payload["changed_files"][:100]
    if len(json.dumps(payload)) > MAX_EVIDENCE_CHARS:
        payload = {
            "scenario_summary": scenario_summary[:1000],
            "changed_files": payload["changed_files"][:20],
            "policy": payload["policy"],
            "security_findings": payload["security_findings"][:20],
            "api_findings": payload["api_findings"][:20],
            "performance": payload["performance"],
            "evidence_truncated": True,
        }
    return payload


def validate_output(raw: Dict[str, Any], report: EvidenceReport, policy: PolicyResult,
                    provider: str, model: str) -> AIAnalysis:
    required = ("summary", "decision", "confidence", "affected_components", "evidence_references",
                "prioritized_findings", "recommended_action", "rollback_plan", "limitations")
    if not isinstance(raw, dict) or any(field not in raw for field in required):
        raise ValueError("analyst output is missing required fields")
    if not isinstance(raw["summary"], str) or not isinstance(raw["recommended_action"], str):
        raise ValueError("analyst text fields must be strings")
    list_fields = ("affected_components", "evidence_references", "prioritized_findings", "rollback_plan", "limitations")
    if any(not isinstance(raw[field], list) or any(not isinstance(item, str) for item in raw[field])
           for field in list_fields):
        raise ValueError("analyst list fields must contain strings")
    decision = Decision(raw["decision"])
    if isinstance(raw["confidence"], bool) or not isinstance(raw["confidence"], (int, float)) or not 0 <= raw["confidence"] <= 1:
        raise ValueError("confidence must be between 0 and 1")
    refs = list(raw["evidence_references"])
    unsupported = unsupported_references(refs, report, policy)
    if unsupported:
        raise ValueError("unsupported evidence references: " + ", ".join(unsupported))
    effective = stricter_decision(policy.status, decision)
    limitations = list(raw["limitations"])
    if effective != decision:
        limitations.append(f"Model decision {decision.value} was constrained by deterministic policy {policy.status.value}.")
    return AIAnalysis(str(raw["summary"]), effective, float(raw["confidence"]), list(raw["affected_components"]),
                      refs, list(raw["prioritized_findings"]), str(raw["recommended_action"]),
                      list(raw["rollback_plan"]), limitations, provider, model, PROMPT_VERSION,
                      datetime.now(timezone.utc).isoformat())


def unsupported_references(references: List[str], report: EvidenceReport, policy: PolicyResult) -> List[str]:
    valid = {"changed_files", "tests", "security_findings", "api_findings", "performance", "errors", "policy"}
    valid.update(f"tools.{tool.name}" for tool in report.tools)
    valid.update(policy.evidence_references)
    return [reference for reference in references if reference not in valid]


def stricter_decision(policy: Decision, model: Decision) -> Decision:
    rank = {Decision.APPROVE: 0, Decision.REVIEW: 1, Decision.BLOCK: 2}
    return policy if rank[policy] >= rank[model] else model


def fallback_analysis(report: EvidenceReport, policy: PolicyResult, provider: str, model: str,
                      limitations: List[str]) -> AIAnalysis:
    refs = policy.evidence_references or ["changed_files"]
    findings = [reason.message for reason in policy.reasons]
    return AIAnalysis(
        summary=f"No analyst model result was available. Deterministic policy remains {policy.status.value}.",
        decision=policy.status,
        confidence=1.0,
        affected_components=report.changed_files,
        evidence_references=refs,
        prioritized_findings=findings,
        recommended_action="Follow the deterministic policy reasons and rerun unavailable checks.",
        rollback_plan=["Restore the previous commit if the release must be withdrawn."],
        limitations=limitations,
        provider=provider,
        model=model,
        prompt_version=PROMPT_VERSION,
        generated_at=datetime.now(timezone.utc).isoformat(),
    )


def _sanitize(value: str) -> str:
    value = re.sub(r"(?i)(password|secret|token|api[_ -]?key)\s*[:=]\s*[^\s,;]+", r"\1=[REDACTED]", value)
    return value


def _system_prompt() -> str:
    return ("Return only the required JSON analyst schema. Use only supplied evidence references. "
            "Never invent measurements, findings, commands, or remediation results. "
            "The deterministic policy decision is authoritative.")
